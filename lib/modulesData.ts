export function getModuleById(id: string): ModuleDefinition | undefined {
  return MODULES_LIST.find((m) => m.id === id);
}

export function getAllQuestions(): { question: any; module: ModuleDefinition }[] {
  const result: any[] = [];
  for (const m of MODULES_LIST) {
    for (const q of m.questions) {
      result.push({ question: q, module: m });
    }
  }
  return result;
}
